#!/usr/bin/env node
// Generate lib/skill-content.js from the plugin's single source of truth,
// skills/hareparse-grammar/SKILL.md. Run from the plugin directory:
//   node scripts/build.mjs
// The generated module is committed so installing the plugin never needs a
// build step; regenerate it after editing the skill.
//
// The integration note is prepended to the skill body so the model always sees
// which DeepSeek Harness tools implement the workflow, even when the skill text
// is reused by another host.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pluginRoot = resolve(here, '..')
const skillPath = process.env.HAREPARSE_SKILL_PATH
  ? resolve(process.env.HAREPARSE_SKILL_PATH)
  : join(pluginRoot, 'skills', 'hareparse-grammar', 'SKILL.md')

const raw = readFileSync(skillPath, 'utf8')
const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(raw)
if (!match) throw new Error(`${skillPath}: 缺少 YAML frontmatter`)
const frontmatter = match[1]
const body = raw.slice(match[0].length)

const descriptionLine = frontmatter.split(/\r?\n/).find((line) => line.startsWith('description:'))
if (descriptionLine === undefined) throw new Error(`${skillPath}: frontmatter 缺少 description`)
const description = descriptionLine.slice('description:'.length).trim().replace(/^["']|["']$/g, '')
if (description === '') throw new Error(`${skillPath}: frontmatter description 为空`)

const integrationNote = `> 本 Skill 由 DeepSeek Harness 的 \`hareparse-grammar\` 插件注册。插件自带真实 HareParse 生成器（\`bin/HareParse.exe\`）与起步模板，不依赖仓库路径或系统 \`PATH\`。优先使用插件工具，而不是自己拼 shell 命令：
>
> - \`hareparse_write_grammar\`：写入完整 \`.gram\`，默认立即 \`--check\`。
> - \`hareparse_check\`：只做内存校验（冲突、缺动作、正则兼容性），不写产物。
> - \`hareparse_generate\`：生成 10 个目标 / 16 种模式的解析器工程；不传 \`lang\`/\`mode\` 时尊重 \`%lang\`/\`%mode\`。
> - \`hareparse_parse_text\`：用 Python 产物解析整段文本，回状态、错误行列、语义值、语法树、\`%commit\`。
> - \`hareparse_run\`：构建并运行生成目录的演示程序（C / C++17 / Python / C# / Rust / Go / Java / JS）。
> - \`hareparse_man\`：查构建期内嵌手册（指令 / 模式 / 语言 / 示例 / 章节 / 关键词）。
> - \`hareparse_dump\`：LR 自动机、SLR 表、Mermaid、\`%epilogue\`/\`%main\` 段、\`%if\` 预处理文本。
> - \`hareparse_clear\`：按产物清单清理生成目录。
>
> 路径从当前会话工作目录解析；写入默认限制在工作目录内。分析阶段先用 \`--lang python\` 跑通结构，交付再换 C / C++17 等目标。语法通过只说明文本形状正确，不说明业务语义、协议状态或数值来源正确。

`

const content = integrationNote + body.trim() + '\n'
const output = `// Generated by scripts/build.mjs from skills/hareparse-grammar/SKILL.md.
// Do not edit by hand; edit the skill source and run the build script.

export const skillDescription = ${JSON.stringify(description)}
export const skillContent = ${JSON.stringify(content)}
`

mkdirSync(join(pluginRoot, 'lib'), { recursive: true })
writeFileSync(join(pluginRoot, 'lib', 'skill-content.js'), output, 'utf8')
console.log(`wrote lib/skill-content.js from ${skillPath}`)
